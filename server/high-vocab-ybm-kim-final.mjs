const makeBook = (lesson, entries, place) => {
  const { prefix, ...school } = place;
  const bookId = `${prefix}:lesson${lesson}`;
  const tags = { ...school, exam_period: YBM_KIM_FINAL_PERIOD };
  return {
    id: bookId, ...tags,
    title: `공통영어2 YBM(김은형) ${lesson}과 본문 (기말고사)`, source: 'exam4you_word_test_2026_10',
    words: entries.map(([word, meaning, part_of_speech, accepted_meanings = []], index) => ({
      id: `${bookId}:${String(index + 1).padStart(3, '0')}`, book_id: bookId, ...tags,
      range_code: `L${lesson}`, order: index + 1, word, meaning, part_of_speech,
      ...(accepted_meanings.length ? { accepted_meanings } : {})
    }))
  };
};

