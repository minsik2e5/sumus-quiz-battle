const makeBook = (lesson, entries) => {
  const bookId = `middle:ybm-park:grade2:lesson${lesson}`;
  return {
    id: bookId,
    school_id: 'wonil-middle',
    school: '원일중',
    division: 'middle',
    grade: '중2',
    title: `중2 YBM(박준언) ${lesson}과`,
    source: 'teacher_source_word_test',
    words: entries.map(([word, meaning, accepted_meanings = []], index) => ({
      id: `${bookId}:${String(index + 1).padStart(3, '0')}`,
      book_id: bookId,
      school_id: 'wonil-middle',
      school: '원일중',
      division: 'middle',
      grade: '중2',
      range_code: String(lesson),
      order: index + 1,
      word,
      meaning,
      ...(accepted_meanings.length ? { accepted_meanings } : {})
    }))
  };
};

